  const seoBlock = SEO_PLATFORMS.includes(platform) ? SEO_RULES : '';
  const cached = `Ты редактор и автор контента платформы LeadGet.
${COMMON_RULES}
${PLATFORM_RULES[platform]}
${seoBlock}${toneBlock(tone)}`;
  const dynamic = `ИСХОДНАЯ НОВОСТЬ (используй как повод и фактическую базу для статьи, не источник для копирования):
Заголовок: ${c.title}
Источник: ${c.source}
Ссылка: ${c.link}
Содержание: ${c.description?.slice(0, 3000) ?? ''}

ВАЖНО: не копируй формулировки, предложения и абзацы из "Содержание" выше. Перескажи факты своими словами, это статья ПО МОТИВАМ новости с собственным анализом и позицией LeadGet, а не пересказ/копия чужого материала.

Выведи ТОЛЬКО итоговый результат по указанному формату. Без комментариев и пояснений.`;
