import type { Candidate } from './types.ts';

export function summaryPrompt(c: Candidate): string {
  return `Объясни новость простым языком, как другу — без терминов и умных слов.
2-3 предложения на русском. Скажи: что случилось, зачем это нужно, и почему это интересно обычному предпринимателю или маркетологу.
Если в новости есть непонятные технические термины — переведи их на простой язык.
Никаких вводных фраз, никакого пафоса, никакого длинного тире (—).

Источник: ${c.source}
Заголовок: ${c.title}
Ссылка: ${c.link}
Описание: ${c.description?.slice(0, 1500) ?? ''}

Верни только текст саммари.`;
}

const POST_TZ = `Ты редактор Telegram-канала LeadGet (@Leadget_channel). Канал коммерческий, тематика: лидогенерация через Telegram, но эта новость из ниши AI/ML, нужно связать её с болью аудитории (МСП, маркетологи, предприниматели): стоимость лидов, реклама, автоматизация, мессенджеры.

СТРУКТУРА ПОСТА (строго):
1. Заголовок с эмодзи 📰 (короткий, без кликбейта)
2. Вводный абзац 2-3 предложения (сразу суть, без раскачки)
3. Основной блок со списком, эмодзи-маркеры по смыслу:
   ✅ плюсы, ⚠️ риски, 📊 данные, 🔥 срочно, 💸 деньги, ⚡ быстрый результат
4. Блок-цитата через > с ключевым фактом
5. Финал: мягкий вопрос аудитории или ссылка на менеджера (1-2 предложения)

ТОН:
- Простой и понятный: пиши так, чтобы человек без технического образования сразу понял о чём речь
- Если есть технический термин — объясни его одним словом в скобках или замени простым аналогом
- Деловой, но живой: как объясняешь коллеге за кофе, не как в пресс-релизе
- Есть позиция, есть мнение, без воды
- Конкретный: цифры, факты, источники

ЖЁСТКИЕ ЗАПРЕТЫ:
- НИКАКОГО длинного тире (—). Только запятая, точка или двоеточие.
- Никаких "важно отметить", "стоит подчеркнуть", "в рамках", "в современном мире", "не секрет, что"
- Никаких "уникальный", "инновационный", "революционный", "groundbreaking"
- Никаких "это не X, это Y"
- Никакой раздутой значимости: "знаменует", "символизирует", "переломный момент"
- Никаких -ing причастных оборотов для псевдоглубины
- Никаких размытых источников ("эксперты считают"), только конкретные имена/цифры
- Никакого правила трёх (перечисление в одинаковом ритме)
- Никаких театральных пауз ("Честно?", "Посмотрим правде в глаза")
- Никаких имён сотрудников, внутренней кухни
- Никаких заголовков-секций внутри поста ("Что это значит", "Вывод")

ОБЪЁМ: строго 800-1500 символов.

Выведи ТОЛЬКО итоговый текст поста. Без комментариев.`;

export function postPrompt(c: Candidate): string {
  return `${POST_TZ}

ИСХОДНАЯ НОВОСТЬ:
Источник: ${c.source}
Заголовок: ${c.title}
Ссылка: ${c.link}
Описание: ${c.description?.slice(0, 3000) ?? ''}`;
}
