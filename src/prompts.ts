export function casePostPrompt(niche: string, task: string, mechanics: string, marketComparison?: string): string {
  const comparisonBlock = marketComparison
    ? `[Сравнение с рынком] Впиши ровно этот факт своими словами, не добавляя других цифр: ${marketComparison}`
    : '[Сравнение с рынком] Данных нет — пропусти этот блок полностью, ни слова про другие каналы или их цену.';
  const tz = CASE_TZ.replace('{{MARKET_COMPARISON}}', comparisonBlock);
  return `${tz}

ДАННЫЕ КЕЙСА:
Ниша: ${niche}
Задача: ${task}
Механика: ${mechanics}

ВАЖНО: В блоке "↗️ Итоги" оставь строго метку <<RESULTS>> — ничего больше. Эта метка будет заменена готовым блоком цифр автоматически.`;
}

